{#
    Расстояние по большому кругу между двумя точками, в километрах.

    В исходном ДЗ у транзакции были координаты клиента и мерчанта (lat/lon
    и merchant_lat/merchant_lon). В Olist координат в заказе нет, но их можно
    восстановить: geolocation даёт центроид по zip-префиксу, а префикс есть
    и у покупателя, и у продавца. Так появляется customer_seller_distance_km —
    и вместе с ним ответ на вопрос, растёт ли просрочка с расстоянием.

    Формула гаверсинуса; радиус Земли взят средний, 6371 км. Тригонометрия
    (radians, sin, cos, asin, sqrt) одинаково называется в ClickHouse и DuckDB,
    поэтому диспетчеризация не нужна.

    Аргументы — УЖЕ В РАДИАНАХ. Перевод вынесен в вызывающую модель
    (int_order_distance) намеренно: собранное в одно выражение вместе
    с переводом градусов, формула упирается в ограничения разборщиков —
    ClickHouse отдаёт «Maximum amount of backtracking exceeded», sqlfluff
    на диалекте duckdb — «Maximum parse depth exceeded». Предподсчёт
    в CTE делает выражение плоским и заодно читаемым.

    NULL не проверяем отдельно: он сам протекает через арифметику и в NULL же
    превращает результат — в обоих движках. Отдельный CASE был бы лишним
    и только добавил бы вложенности.

    Использование:
        {{ haversine_km('c_lat_rad', 'c_lon_rad', 's_lat_rad', 's_lon_rad') }}
#}

{% macro haversine_km(lat1_rad, lon1_rad, lat2_rad, lon2_rad) %}
    12742 * asin(sqrt(
        sin(({{ lat2_rad }} - {{ lat1_rad }}) / 2) * sin(({{ lat2_rad }} - {{ lat1_rad }}) / 2)
        + cos({{ lat1_rad }}) * cos({{ lat2_rad }})
        * sin(({{ lon2_rad }} - {{ lon1_rad }}) / 2) * sin(({{ lon2_rad }} - {{ lon1_rad }}) / 2)
    ))
{% endmacro %}
