{#
    Координаты, схлопнутые до одной точки на zip-префикс.

    Сырая таблица — 1 000 163 строки на 19 015 префиксов, в среднем 53 точки
    на префикс. Присоединить её к клиентам как есть означает размножить
    каждый заказ в полсотни раз: выручка вырастет на два порядка, и это
    не бросится в глаза сразу.

    ДВЕ ЧИСТКИ, обе обязательные:

    1. Схлопывание в центроид (среднее по широте и долготе) — снимает
       размножение строк.

    2. Отсев координат за пределами Бразилии. В датасете есть точки
       с широтой до 42° и долготой до +121° — это Азия, а не Бразилия.
       Таких префиксов 11 из 19 015, но одна такая точка растягивает
       расстояние «покупатель ↔ продавец» до 8 678 км при том, что
       максимальный размах страны около 4 400 км. Среднее расстояние
       по штату после этого уже ничего не значит.

       Отсекаем ДО усреднения, а не после: иначе выброс утянет центроид
       за собой, и испорченным окажется весь префикс.

    Границы Бразилии с запасом: широта -34…6, долгота -74…-34.

    Город и штат берём через min(), а не any()/any_value(): у ClickHouse
    и DuckDB эти функции называются по-разному, а min() есть в обоих
    и вдобавок детерминирован.
#}

with source as (
    select * from {{ source('olist_raw', 'geolocation') }}
),

within_brazil as (
    select *
    from source
    where
        geolocation_lat between -34.0 and 6.0
        and geolocation_lng between -74.0 and -34.0
)

select
    geolocation_zip_code_prefix as zip_code_prefix,

    avg(geolocation_lat) as latitude,
    avg(geolocation_lng) as longitude,

    min(geolocation_city) as city,
    min(geolocation_state) as state,

    count(*) as points_cnt

from within_brazil
group by geolocation_zip_code_prefix
